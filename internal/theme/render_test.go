// Every generated file carries the header, which is what stops someone editing
// the output instead of the palette.
func TestRenderersEmitTheGeneratedBanner(t *testing.T) {
	home := fixtureHome(t)
	th := loadFixture(t)

	cases := []struct {
		name string
		fn   func(*Theme) error
		out  string
	}{
		{"quickshell", renderQuickshell, ".config/quickshell/generated/Colors.qml"},
		{"kitty", renderKitty, ".config/kitty/theme.conf"},
		{"alacritty", renderAlacritty, ".config/alacritty/colors.toml"},
		{"nvim", renderNvim, ".config/nvim/lua/theme.lua"},
		{"doom", renderDoom, ".config/doom/theme.el"},
		{"btop", renderBtop, ".config/btop/themes/fixture.theme"},
		{"hyprpaper", renderHypr, ".config/hypr/hyprpaper.conf"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if err := c.fn(th); err != nil {
				t.Fatalf("render: %v", err)
			}
			got := readFile(t, filepath.Join(home, c.out))
			if !strings.Contains(got, "GENERATED by ~/.config/theme") {
				t.Errorf("no GENERATED banner in %s", c.out)
			}
		})
	}
}

// Rendering twice must produce identical bytes — the switcher runs on every
// Hyprland start, and chezmoi diffs several of these files.
func TestRenderersAreDeterministic(t *testing.T) {
	home := fixtureHome(t)
	th := loadFixture(t)

	outputs := []string{
		".config/quickshell/generated/Colors.qml",
		".config/kitty/theme.conf",
		".config/alacritty/colors.toml",
		".config/nvim/lua/theme.lua",
		".config/doom/theme.el",
		".config/btop/themes/fixture.theme",
		".config/hypr/hyprpaper.conf",
		".config/hypr/colors.conf",
	}
	render := func() map[string]string {
		for _, r := range []func(*Theme) error{
			renderQuickshell, renderKitty, renderAlacritty, renderNvim,
			renderDoom, renderBtop, renderHypr,
		} {
			if err := r(th); err != nil {
				t.Fatalf("render: %v", err)
			}
		}
		out := map[string]string{}
		for _, o := range outputs {
			out[o] = readFile(t, filepath.Join(home, o))
		}
		return out
	}

	first := render()
	for range 3 {
		for path, content := range render() {
			if content != first[path] {
				t.Errorf("%s changed between renders of the same palette", path)
			}
		}
	}
}

