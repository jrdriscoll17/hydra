// The renderers write files other programs parse, and several of them are
// diffed against the config repo, so the contract is the exact bytes rather
// than "contains the right colours". These goldens are that contract: a diff
// here means a generated config changed shape, which is worth a deliberate
// look before `-update` blesses it.
var update = flag.Bool("update", false, "rewrite the golden files in testdata")

func golden(t *testing.T, name, got string) {
	t.Helper()
	path := filepath.Join("testdata", name+".golden")

	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading golden %s: %v\n(run `go test ./internal/theme -update` to create it)", path, err)
	}
	if want := string(raw); got != want {
		t.Errorf("%s does not match its golden file.\n--- got ---\n%s\n--- want ---\n%s", name, got, want)
	}
}

// renderTo runs one renderer against the fixture palette in a temp HOME and
// returns the file it wrote.
func renderTo(t *testing.T, fn func(*Theme) error, out string) string {
	t.Helper()
	home := fixtureHome(t)
	th := loadFixture(t)
	if err := fn(th); err != nil {
		t.Fatalf("render: %v", err)
	}
	return readFile(t, filepath.Join(home, out))
}

func TestRenderQuickshell(t *testing.T) {
	got := renderTo(t, renderQuickshell, ".config/quickshell/generated/Colors.qml")
	golden(t, "Colors.qml", got)

	// The property list must follow the palette's own order, since that is the
	// only thing keeping this file stable between runs.
	first := strings.Index(got, "property color base:")
	last := strings.Index(got, "property color accent:")
	if first < 0 || last < 0 || first > last {
		t.Error("colour properties are not emitted in palette order")
	}
}

