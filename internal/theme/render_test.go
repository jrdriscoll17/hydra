// The theme file is generated whole, but btop.conf belongs to btop and is only
// retargeted — hand-made settings in it have to survive.
func TestRenderBtopRetargetsConfWithoutTouchingTheRest(t *testing.T) {
	home := fixtureHome(t)
	th := loadFixture(t)

	writeFile(t, filepath.Join(home, ".config/btop/btop.conf"), strings.Join([]string{
		`#? Config file for btop`,
		`color_theme = "/some/old/theme.theme"`,
		`theme_background = False`,
		`update_ms = 2000`,
		``,
	}, "\n"))

	if err := renderBtop(th); err != nil {
		t.Fatalf("renderBtop: %v", err)
	}

	got := readFile(t, filepath.Join(home, ".config/btop/btop.conf"))
	want := `color_theme = "` + home + `/.config/btop/themes/fixture.theme"`
	if !strings.Contains(got, want) {
		t.Errorf("color_theme not retargeted:\n%s", got)
	}
	for _, keep := range []string{"theme_background = False", "update_ms = 2000", "#? Config file for btop"} {
		if !strings.Contains(got, keep) {
			t.Errorf("btop.conf lost %q:\n%s", keep, got)
		}
	}
}

