// libadwaita apps ignore the theme name and read ~/.config/gtk-4.0/gtk.css, so
// the switcher symlinks it out of whichever theme the palette names for gtk4.
func TestRenderGTKLinksGTK4Sheets(t *testing.T) {
	home := fixtureHome(t)
	th := loadFixture(t)

	src := filepath.Join(home, ".themes", "Colloid-Teal-Dark-Nord", "gtk-4.0")
	writeFile(t, filepath.Join(src, "gtk.css"), "/* gtk4 */")
	writeFile(t, filepath.Join(src, "gtk-dark.css"), "/* gtk4 dark */")

	if err := renderGTK(th); err != nil {
		t.Fatalf("renderGTK: %v", err)
	}

	for _, css := range []string{"gtk.css", "gtk-dark.css"} {
		link := filepath.Join(home, ".config/gtk-4.0", css)
		target, err := os.Readlink(link)
		if err != nil {
			t.Errorf("%s is not a symlink: %v", css, err)
			continue
		}
		if want := filepath.Join(src, css); target != want {
			t.Errorf("%s -> %q, want %q", css, target, want)
		}
	}
}

func TestRenderGTKReplacesAStaleGTK4Link(t *testing.T) {
	home := fixtureHome(t)
	th := loadFixture(t)

	src := filepath.Join(home, ".themes", "Colloid-Teal-Dark-Nord", "gtk-4.0")
	writeFile(t, filepath.Join(src, "gtk.css"), "/* gtk4 */")

	// A link left behind by the previous theme.
	stale := filepath.Join(home, ".config/gtk-4.0", "gtk.css")
	mkdir(t, filepath.Dir(stale))
	if err := os.Symlink(filepath.Join(home, ".themes/Old/gtk-4.0/gtk.css"), stale); err != nil {
		t.Fatal(err)
	}

	if err := renderGTK(th); err != nil {
		t.Fatalf("renderGTK: %v", err)
	}
	target, err := os.Readlink(stale)
	if err != nil {
		t.Fatalf("gtk.css is not a symlink: %v", err)
	}
	if want := filepath.Join(src, "gtk.css"); target != want {
		t.Errorf("stale link not replaced: -> %q, want %q", target, want)
	}
}

