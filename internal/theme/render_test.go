// fakeKvantumBase installs a stock Kvantum theme for renderQt to borrow.
func fakeKvantumBase(t *testing.T) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "Nordic-Darker-Solid")
	writeFile(t, filepath.Join(dir, "Nordic-Darker-Solid.kvconfig"), strings.Join([]string{
		`[%General]`,
		`author=Someone`,
		`x11drag=menubar_and_primary_toolbar`,
		``,
		`[GeneralColors]`,
		`window.color=#111111`,
		`base.color=#222222`,
		``,
		`[Hacks]`,
		`transparent_dolphin_view=true`,
		``,
	}, "\n"))
	writeFile(t, filepath.Join(dir, "Nordic-Darker-Solid.svg"), "<svg>widgets</svg>")

	original := kvantumBase
	kvantumBase = dir
	t.Cleanup(func() { kvantumBase = original })
	return dir
}

func TestRenderQt(t *testing.T) {
	home := fixtureHome(t)
	fakeKvantumBase(t)
	th := loadFixture(t)

	if err := renderQt(th); err != nil {
		t.Fatalf("renderQt: %v", err)
	}

	t.Run("the palette gets its own kvconfig", func(t *testing.T) {
		got := readFile(t, filepath.Join(home, ".config/Kvantum/Fixture/Fixture.kvconfig"))
		if !strings.Contains(got, "highlight.color=#111111") {
			t.Errorf("accent not written into GeneralColors:\n%s", got)
		}
		if !strings.Contains(got, "window.color=#010101") {
			t.Errorf("base colour not written:\n%s", got)
		}
		// The rest of the stock theme has to survive: [GeneralColors] is the
		// only block being replaced.
		for _, keep := range []string{"[%General]", "x11drag=menubar_and_primary_toolbar", "[Hacks]"} {
			if !strings.Contains(got, keep) {
				t.Errorf("kvconfig lost %q from the base:\n%s", keep, got)
			}
		}
		if strings.Contains(got, "#222222") {
			t.Errorf("a base GeneralColors value survived:\n%s", got)
		}
	})

	t.Run("the widget SVG is copied", func(t *testing.T) {
		if got := readFile(t, filepath.Join(home, ".config/Kvantum/Fixture/Fixture.svg")); got != "<svg>widgets</svg>" {
			t.Errorf("SVG = %q", got)
		}
	})

	t.Run("kvantum is pointed at the theme", func(t *testing.T) {
		got := readFile(t, filepath.Join(home, ".config/Kvantum/kvantum.kvconfig"))
		if !strings.Contains(got, "theme=Fixture") {
			t.Errorf("kvantum.kvconfig:\n%s", got)
		}
	})

	// This is what gives Qt an icon theme at all, Quickshell included.
	t.Run("qt5ct and qt6ct are configured", func(t *testing.T) {
		for _, qt := range []string{"qt5ct", "qt6ct"} {
			got := readFile(t, filepath.Join(home, ".config", qt, qt+".conf"))
			for _, want := range []string{
				"[Appearance]", "icon_theme=MB-Fixture-Suru-GLOW",
				"style=kvantum", "standard_dialogs=default",
			} {
				if !strings.Contains(got, want) {
					t.Errorf("%s.conf missing %q:\n%s", qt, want, got)
				}
			}
		}
	})
}

