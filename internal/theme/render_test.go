// renderQuickshell must stay last: writing Colors.qml hot-reloads Quickshell,
// which tears down the QML engine and kills the process the picker spawned.
func TestQuickshellRendersLast(t *testing.T) {
	if len(renderers) == 0 {
		t.Fatal("no renderers registered")
	}
	if got := renderers[len(renderers)-1].name; got != "quickshell" {
		t.Errorf("last renderer is %q, want \"quickshell\" — writing Colors.qml "+
			"hot-reloads the shell and kills this process, so it has to come after "+
			"everything else has landed", got)
	}
}

func TestRendererNamesAreUnique(t *testing.T) {
	seen := map[string]bool{}
	for _, r := range renderers {
		if seen[r.name] {
			t.Errorf("duplicate renderer name %q", r.name)
		}
		seen[r.name] = true
		if r.fn == nil {
			t.Errorf("renderer %q has no function", r.name)
		}
	}
}
